CREATE TABLE IF NOT EXISTS medical_price_item (
  item_id        BIGINT(20)    NOT NULL AUTO_INCREMENT COMMENT '价目ID',
  item_type      VARCHAR(20)   NOT NULL              COMMENT '项目类别（挂号费/诊查费/检查费/化验费/治疗费/手术费/护理费/床位费/药品/其它）',
  item_name      VARCHAR(100)  NOT NULL              COMMENT '项目名称',
  spec           VARCHAR(100)  DEFAULT ''            COMMENT '规格/说明',
  unit           VARCHAR(20)   DEFAULT ''            COMMENT '计价单位',
  price          DECIMAL(10,2) DEFAULT 0.00          COMMENT '价格（元）',
  insurance_flag CHAR(1)       DEFAULT '1'           COMMENT '医保标记（0自费 1医保）',
  status         CHAR(1)       DEFAULT '0'           COMMENT '状态（0启用 1停用）',
  remark         VARCHAR(200)  DEFAULT NULL          COMMENT '备注',
  PRIMARY KEY (item_id),
  KEY idx_price_type (item_type)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8mb4 COMMENT='医疗费用价目表';

